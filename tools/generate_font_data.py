#!/usr/bin/env python3
"""Build-time font data generator (NOT run by the entry).

Renders the glyphs of DejaVu Sans (Book + Bold) at 64 px with Pillow and
writes them as compact hex bitmaps into font_data.py, one line per glyph.
DejaVu Sans is free (Bitstream Vera licence) and ships with the system.

Run once while building the entry:
    python3 tools/generate_font_data.py
The entry itself (main.py) is pure standard library and only reads the
generated font_data.py; it never touches Pillow or any font file.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

MASTER = 64
FONTS = {
    "REGULAR": "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "BOLD": "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
}

# Printable ASCII plus the punctuation this front page uses.
CHARS = list(range(32, 127)) + [0x2013, 0x2014, 0x2018, 0x2019,
                                0x201C, 0x201D, 0x00B7, 0x00D7]


def glyph(font, code):
    """Return (advance, width, height, left, top, hex) for one glyph."""
    ch = chr(code)
    adv = int(round(font.getlength(ch)))
    # Render onto a scratch image: getmask returns an ImagingCore, so draw
    # the glyph instead and crop to its ink box.
    pad = 4
    scratch = Image.new("L", (adv + 2 * pad, MASTER + 2 * pad), 0)
    ImageDraw.Draw(scratch).text((pad, pad), ch, font=font, fill=255)
    bbox = scratch.getbbox()
    if bbox is None:  # space and other blank glyphs
        return adv, 0, 0, 0, 0, ""
    left, top, right, bottom = bbox
    w, h = right - left, bottom - top
    # left/top are relative to the em box whose top edge is at pad.
    return adv, w, h, left - pad, top - pad, scratch.crop(bbox).tobytes().hex()


def main():
    out_path = os.path.join(os.path.dirname(__file__), "..", "font_data.py")
    lines = []
    lines.append("# Glyph bitmaps for DejaVu Sans (Book and Bold), rendered at "
                 "64 px.")
    lines.append("# Generated by tools/generate_font_data.py; see that file.")
    lines.append("# Format per glyph: code -> (advance, width, height, left, "
                 "top, hex coverage).")
    lines.append("# advance/width/height/left/top are in 64 px master units; "
                 "main.py scales them.")
    lines.append("")
    for name, path in FONTS.items():
        font = ImageFont.truetype(path, MASTER)
        lines.append("%s = {" % name)
        for code in CHARS:
            adv, w, h, left, top, hx = glyph(font, code)
            lines.append("    %d: (%d, %d, %d, %d, %d, \"%s\")," %
                         (code, adv, w, h, left, top, hx))
        lines.append("}")
        lines.append("")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    size = os.path.getsize(out_path)
    print("wrote %s (%d bytes, %d glyphs x %d fonts)"
          % (out_path, size, len(CHARS), len(FONTS)))


if __name__ == "__main__":
    sys.exit(main())
